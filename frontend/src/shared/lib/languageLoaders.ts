export async function loadLazyLanguage(
  language: LazyLanguage,
): Promise<Record<string, unknown>> {
  const loaders = LANGUAGE_LOADERS[language];
  if (!loaders) {
    throw new Error(`No loader registered for locale "${language}"`);
  }
  const modules = await Promise.all(loaders.map((load) => load()));
  return Object.assign({}, ...modules.map((module) => module.default));
}
