#!/usr/bin/env bash
#
# Writes backend/database/baseline.sql, the schema (plus the schools, email
# domains and site banner rows) scripts/migrate-database.sh builds an empty
# database from, by dumping DATABASE_URL.
#
# The database's public.schema_migrations must record exactly the files in
# backend/database/migrations, so the baseline holds every migration up to the
# newest one; that version goes in the file's "-- baseline-version:" header.
#
# Usage: DATABASE_URL=postgresql://... scripts/dump-schema-baseline.sh

set -euo pipefail

if [ "$#" -ne 0 ]; then
  echo "Usage: DATABASE_URL=<postgres url> $0" >&2
  exit 2
fi

database_url="${DATABASE_URL:?DATABASE_URL is required}"
repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
migrations_dir="$repo_root/backend/database/migrations"
baseline="$repo_root/backend/database/baseline.sql"

fail() {
  echo "dump-schema-baseline: $1" >&2
  exit 1
}

query() {
  psql --dbname="$database_url" --no-psqlrc --quiet -v ON_ERROR_STOP=1 \
    --tuples-only --no-align --command="$1"
}

has_history="$(query "SELECT to_regclass('public.schema_migrations') IS NOT NULL")"
[ "$has_history" = t ] ||
  fail "public.schema_migrations does not exist; run scripts/migrate-database.sh against this database first."

file_versions="$(
  shopt -s nullglob
  for file in "$migrations_dir"/*.sql; do
    file_name="${file##*/}"
    echo "${file_name%%_*}"
  done | LC_ALL=C sort
)"
[ -n "$file_versions" ] || fail "No migration files in $migrations_dir."
recorded="$(query 'SELECT version FROM public.schema_migrations' | LC_ALL=C sort)"
if [ "$recorded" != "$file_versions" ]; then
  echo "dump-schema-baseline: public.schema_migrations does not match backend/database/migrations (< only in the database, > only in files):" >&2
  diff <(echo "$recorded") <(echo "$file_versions") >&2 || true
  fail "Apply pending migrations with scripts/migrate-database.sh, then dump again."
fi
baseline_version="${file_versions##*$'\n'}"

# A pg_dump from another major version can write syntax the server's version
# does not accept, so the baseline would not apply where it came from.
server_version_num="$(query 'SHOW server_version_num')"
server_major="$((server_version_num / 10000))"
dump_version="$(pg_dump --version)"
dump_major="$(sed -E 's/^pg_dump \(PostgreSQL\) ([0-9]+).*/\1/' <<<"$dump_version")"
[ "$dump_major" = "$server_major" ] ||
  fail "$dump_version does not match the server's PostgreSQL $server_major; use pg_dump $server_major."

# Roles belong to the server rather than the database, so a dump does not
# create them, yet row-level security policies name them. Creating each one
# (without a login) lets the baseline apply to a new server.
roles_sql="$(
  cat <<'SQL'
SELECT format(
    'DO $$ BEGIN IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = %L) THEN CREATE ROLE %I NOLOGIN%s; END IF; END $$;',
    rolname, rolname, CASE WHEN rolbypassrls THEN ' BYPASSRLS' ELSE '' END)
FROM pg_catalog.pg_roles
WHERE oid IN (SELECT unnest(polroles) FROM pg_catalog.pg_policy)
ORDER BY rolname
SQL
)"

temporary="$(mktemp "$baseline.XXXXXX")"
trap 'rm -f "$temporary"' EXIT
{
  echo "-- baseline-version: $baseline_version"
  echo "-- Generated by scripts/dump-schema-baseline.sh; do not edit by hand."
  echo "-- The schema after every migration through that version, which"
  echo "-- scripts/migrate-database.sh applies to an empty database."
  echo
  echo "-- Roles the row-level security policies name."
  query "$roles_sql"
  echo
  # The fixed restrict key keeps a rerun at the same version byte-identical.
  # The runner owns public.schema_migrations and creates it itself.
  pg_dump --dbname="$database_url" --schema-only --no-owner --no-privileges \
    --no-publications --no-subscriptions --no-security-labels --no-tablespaces \
    --exclude-table=public.schema_migrations \
    --restrict-key="baseline$baseline_version"
  echo
  echo "-- Reference rows every environment starts from: the schools, their email"
  echo "-- domains and the site banner. All other data comes from use or seed.sql."
  pg_dump --dbname="$database_url" --data-only --no-owner --no-privileges \
    --table=public.schools --table=public.school_email_domains --table=public.site_banner \
    --restrict-key="baseline$baseline_version"
} >"$temporary"
mv "$temporary" "$baseline"
trap - EXIT
echo "Wrote backend/database/baseline.sql at migration $baseline_version."
